export type IconName = keyof typeof icons;

export function Icon({
  name,
  size = 16,
  strokeWidth = 1.75,
  className = '',
  style,
}: {
  name: IconName;
  size?: number;
  strokeWidth?: number;
  className?: string;
  style?: CSSProperties;
}) {
  const Glyph = icons[name];
  return (
    <Glyph
      className={`ui-icon ${className}`}
      width={size}
      height={size}
      strokeWidth={strokeWidth}
      aria-hidden="true"
      focusable="false"
      style={style}
    />
  );
}
